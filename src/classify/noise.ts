/**
 * noise.ts — automatic e-mails that open a ticket but are not a support request.
 *
 * The motivating case: a mail client's "daily reaction digest" kept arriving as
 * a new ticket. The router classified it like any other ticket, routed it to a
 * squad and, worse, attached a city hall as requester. Every one of them ended
 * up cancelled by hand.
 *
 * The core rule needs TWO signals at once — sender address AND subject — on
 * purpose: the address alone would silence a legitimate notice from the same
 * mail provider; the subject alone would silence a real ticket that quotes it.
 *
 * Pure module. Consumers:
 *  - the processor skips classification and the first reply for noise;
 *  - resolveRoute({ noise }) is the safety net: noise always ends in triage.
 */

import { norm } from "../text/normalize.js";

export const NOISE_TAG = "AUTOMATED NOISE";

export interface NoiseRule {
  name: string;
  /** exact addresses, compared against every client of the ticket */
  emails?: string[];
  /** regex over the normalized address of any client */
  emailRe?: RegExp;
  /** regex over the normalized subject */
  subject?: RegExp;
  /** match on the subject only (auto-replies come from the person's own address) */
  subjectOnly?: boolean;
  /** sender-only block for a loop; meant to be removed once the sender is fixed */
  temporary?: boolean;
  tags: string[];
  label: string;
}

export interface NoiseMatch {
  rule: string;
  label: string;
  tags: string[];
  email: string;
  reason: string;
}

export const NOISE_RULES: NoiseRule[] = [
  {
    name: "mail-daily-reaction-digest",
    emails: ["no-reply@digest.mail.example"],
    // the real subject carries the date ("Daily reaction digest - Wednesday, ...")
    subject: /daily reaction digest/,
    tags: [NOISE_TAG],
    label: "mail provider's automatic digest",
  },
  {
    // TEMPORARY: a vendor's support bot answered our first reply by opening a new
    // ticket, which we answered again — an infinite loop of tickets. Sender-only on
    // purpose (it silences everything from that address) until the vendor fixes it.
    name: "vendor-bot-loop",
    emails: ["helpdesk-bot@vendor.example"],
    temporary: true,
    tags: [NOISE_TAG],
    label: "vendor support bot replying in a loop",
  },
];

/**
 * Extra rules (behind a flag, rolled out after measuring): messages generated by
 * mail servers. Only unambiguous forms — the PREFIX a mail client adds to the
 * subject (quoted mid-subject does not count) or the mail-server mailbox itself.
 */
export const NOISE_RULES_EXTRA: NoiseRule[] = [
  {
    name: "auto-reply",
    subjectOnly: true,
    subject: /^(?:automatic reply|auto(?:matic)?[- ]?reply|autoreply|out of office|away from the office)\s*:/,
    tags: [NOISE_TAG],
    label: "automatic out-of-office reply",
  },
  {
    name: "delivery-failure",
    subjectOnly: true,
    // fixed server subjects only: "Could not deliver the permit to the applicant" is a real ticket
    subject: /^(?:(?:undeliverable|returned mail)\s*:|undelivered mail returned to sender\b|delivery status notification \(failure\)|mail delivery (?:failed|failure)\s*(?::|$|- returning))/,
    tags: [NOISE_TAG],
    label: "mail delivery failure notice",
  },
  {
    name: "mail-server",
    emailRe: /^(?:mailer-daemon|postmaster)@/,
    tags: [NOISE_TAG],
    label: "message from a mail server (mailer-daemon/postmaster)",
  },
];

export function detectNoise(
  input: { subject?: string | null; clients?: Array<{ email?: string | null } | null> | null },
  opts: { extras?: boolean } = {},
): NoiseMatch | null {
  const subjectNorm = norm(input.subject);
  const emails = (input.clients || []).map((c) => norm(c?.email)).filter(Boolean);
  const rules = opts.extras ? [...NOISE_RULES, ...NOISE_RULES_EXTRA] : NOISE_RULES;

  for (const rule of rules) {
    if (rule.subject && !(subjectNorm && rule.subject.test(subjectNorm))) continue;
    let hit: string | undefined;
    if (rule.subjectOnly) hit = emails[0] ?? "";
    else if (rule.emailRe) hit = emails.find((e) => rule.emailRe!.test(e));
    else hit = emails.find((e) => (rule.emails || []).some((addr) => norm(addr) === e));
    if (hit === undefined) continue;
    return {
      rule: rule.name,
      label: rule.label,
      tags: [...rule.tags],
      email: hit,
      reason: `${rule.label} → triage to be cancelled; not a support request`,
    };
  }
  return null;
}
